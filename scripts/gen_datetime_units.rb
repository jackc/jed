#!/usr/bin/env ruby
# frozen_string_literal: true

# Codegen "middle path" (CLAUDE.md §5): generate the per-language datetime unit-name tables
# (PostgreSQL's `deltatktbl` and `datetktbl`) from the canonical spec/types/datetime_units.toml.
# It also emits the SQL interval field-qualifier table (interval.md §6.1). This emits the DATA only — the lookup (ASCII case-fold, TOKMAXLEN truncation, binary
# search) and what EXTRACT / date_part / date_trunc do with the result stay hand-written in each
# core's datetime_fn. Build-time only; no shipped core runs Ruby or parses TOML.
#
#   ruby scripts/gen_datetime_units.rb            # (re)write the generated files
#   ruby scripts/gen_datetime_units.rb --check    # fail if any checked-in file is stale
#
# Reasoning: spec/design/timezones.md §9.6 and spec/design/codegen.md.

require "bundler/setup"
require "toml-rb"

REPO = File.expand_path("..", __dir__)
SRC = File.join(REPO, "spec", "types", "datetime_units.toml")

TARGETS = [
  ["impl/rust/src/datetime_units_gen.rs", :rust_file],
  ["impl/go/datetime_units_gen.go",       :go_file],
  ["impl/ts/src/datetime_units_gen.ts",   :ts_file],
].freeze

# The values a `units` entry may name: the canonical units the datetime kernels match on.
UNIT_VALUES = %w[
  microseconds milliseconds second minute hour day week month quarter year decade century
  millennium timezone timezone_hour timezone_minute julian dow doy isodow isoyear
].freeze
RESERV_VALUES = %w[epoch late early now today tomorrow yesterday zulu].freeze
OTHER_TYPES = %w[ago ignore_dtf month dow ampm adbc isotime dtzmod].freeze

def fail!(msg)
  warn "FAIL: #{msg}"
  exit 1
end

# --- load + validate -----------------------------------------------------------

def load_tables
  data = TomlRB.load_file(SRC)
  max = data["token_max_len"]
  fail!("#{SRC}: token_max_len must be 10 (PostgreSQL's TOKMAXLEN)") unless max == 10
  tables = { "delta" => data["delta"], "date" => data["date"] }
  quals = data["interval_qualifier"]
  validate_qualifiers(quals)
  tables.each do |name, entries|
    fail!("#{SRC}: no #{name} entries") if entries.nil? || entries.empty?
    entries.each { |e| validate_entry(name, e, max) }
    tokens = entries.map { |e| e["token"] }
    # Strictly ascending byte order: PostgreSQL binary-searches each table, and so do the cores.
    tokens.each_cons(2) do |a, b|
      fail!("#{name}: #{a.inspect} must sort before #{b.inspect}") unless a.b < b.b
    end
  end
  [max, tables.merge("qualifier" => quals)]
end

LEAST_FIELDS = %w[year month day hour minute second].freeze

# The thirteen interval qualifiers: codes 1..13 in order (persisted, never renumbered), each name
# a leading field or `<leading> to <trailing>` (single spaces), each least field one of the six.
def validate_qualifiers(quals)
  fail!("#{SRC}: expected 13 interval_qualifier entries") unless quals.is_a?(Array) && quals.length == 13
  quals.each_with_index do |q, i|
    fail!("interval_qualifier #{i}: code must be #{i + 1}") unless q["code"] == i + 1
    unless q["name"].is_a?(String) && q["name"].match?(/\A[a-z]+( to [a-z]+)?\z/)
      fail!("interval_qualifier #{q['code']}: bad name #{q['name'].inspect}")
    end
    fail!("interval_qualifier #{q['name']}: bad least #{q['least'].inspect}") unless LEAST_FIELDS.include?(q["least"])
    fail!("interval_qualifier #{q['name']}: least must end the name") unless q["name"].end_with?(q["least"])
    fail!("interval_qualifier #{q['name']}: mm_ss is a boolean") unless [nil, true, false].include?(q["mm_ss"])
  end
end

def mm_ss(q) = q["mm_ss"] ? "true" : "false"

def validate_entry(table, e, max)
  tok = e["token"]
  fail!("#{table}: entry without a token") unless tok.is_a?(String) && !tok.empty?
  fail!("#{table}: #{tok.inspect} is not lowercase ASCII") unless tok.match?(/\A[\x21-\x7e]+\z/) && tok == tok.downcase
  fail!("#{table}: #{tok.inspect} is longer than #{max} bytes") if tok.bytesize > max
  case e["type"]
  when "units"
    fail!("#{table}: #{tok}: unknown unit #{e['value'].inspect}") unless UNIT_VALUES.include?(e["value"])
  when "reserv"
    fail!("#{table}: #{tok}: unknown reserved value #{e['value'].inspect}") unless RESERV_VALUES.include?(e["value"])
  when *OTHER_TYPES
    fail!("#{table}: #{tok}: a #{e['type']} entry carries no value") if e.key?("value")
  else
    fail!("#{table}: #{tok}: unknown type #{e['type'].inspect}")
  end
end

def value_of(e) = e["value"] || ""

# --- Rust ----------------------------------------------------------------------

def rust_entry(e)
  %(    DtToken { token: "#{e['token']}", kind: "#{e['type']}", value: "#{value_of(e)}" },)
end

def rust_file(max, tables)
  <<~RS
    // @generated by scripts/gen_datetime_units.rb from spec/types/datetime_units.toml — DO NOT EDIT.
    //
    // PostgreSQL's datetime unit-name tables (CLAUDE.md §5): `deltatktbl` (DecodeUnits) and
    // `datetktbl` (DecodeSpecial), as DATA. The lookup that CONSUMES them (case-fold, TOKMAXLEN
    // truncation, binary search) is hand-written in datetime_fn.rs. Regenerate with
    // `mise run codegen`; `mise run verify` fails if this file is stale. Reasoning:
    // ../../../spec/design/timezones.md §9.6.

    /// PostgreSQL's `TOKMAXLEN`: a lookup compares at most this many bytes of the name.
    pub const TOKEN_MAX_LEN: usize = #{max};

    /// One table entry. `kind` is PostgreSQL's token type (`units`, `reserv`, or another type no
    /// unit lookup accepts); `value` is the canonical unit (`units`) or reserved meaning (`reserv`),
    /// empty otherwise.
    pub struct DtToken {
        pub token: &'static str,
        pub kind: &'static str,
        pub value: &'static str,
    }

    /// PostgreSQL's `deltatktbl`, in ascending byte order.
    #[rustfmt::skip]
    pub const DELTA_TOKENS: &[DtToken] = &[
    #{tables['delta'].map { |e| rust_entry(e) }.join("\n")}
    ];

    /// PostgreSQL's `datetktbl`, in ascending byte order.
    #[rustfmt::skip]
    pub const DATE_TOKENS: &[DtToken] = &[
    #{tables['date'].map { |e| rust_entry(e) }.join("\n")}
    ];

    /// One SQL interval field qualifier (interval.md §6.1): its persisted `code`, its `name` as
    /// written and displayed, its least-significant kept field, and whether `a:b` reads as mm:ss.
    pub struct IntervalQualifier {
        pub code: u8,
        pub name: &'static str,
        pub least: &'static str,
        pub mm_ss: bool,
    }

    /// The thirteen interval qualifiers, by ascending code (`INTERVAL_QUALIFIERS[code - 1]`).
    #[rustfmt::skip]
    pub const INTERVAL_QUALIFIERS: &[IntervalQualifier] = &[
    #{tables['qualifier'].map { |q| %(    IntervalQualifier { code: #{q['code']}, name: "#{q['name']}", least: "#{q['least']}", mm_ss: #{mm_ss(q)} },) }.join("\n")}
    ];
  RS
end

# --- Go ------------------------------------------------------------------------

def go_entry(e)
  %(\t{token: "#{e['token']}", kind: "#{e['type']}", value: "#{value_of(e)}"},)
end

def go_file(max, tables)
  <<~GO
    // Code generated by scripts/gen_datetime_units.rb from spec/types/datetime_units.toml. DO NOT EDIT.
    //
    // PostgreSQL's datetime unit-name tables (CLAUDE.md §5): deltatktbl (DecodeUnits) and
    // datetktbl (DecodeSpecial), as DATA. The lookup that CONSUMES them (case-fold, TOKMAXLEN
    // truncation, binary search) is hand-written in datetime_fn.go. Regenerate with
    // `mise run codegen`; `mise run verify` fails if stale. Reasoning:
    // ../../spec/design/timezones.md §9.6.

    package jed

    // dtTokenMaxLen is PostgreSQL's TOKMAXLEN: a lookup compares at most this many bytes of the name.
    const dtTokenMaxLen = #{max}

    // dtToken is one table entry. kind is PostgreSQL's token type ("units", "reserv", or another
    // type no unit lookup accepts); value is the canonical unit ("units") or reserved meaning
    // ("reserv"), empty otherwise.
    type dtToken struct {
    \ttoken string
    \tkind  string
    \tvalue string
    }

    // dtDeltaTokens is PostgreSQL's deltatktbl, in ascending byte order.
    var dtDeltaTokens = []dtToken{
    #{tables['delta'].map { |e| go_entry(e) }.join("\n")}
    }

    // dtDateTokens is PostgreSQL's datetktbl, in ascending byte order.
    var dtDateTokens = []dtToken{
    #{tables['date'].map { |e| go_entry(e) }.join("\n")}
    }

    // intervalQualifier is one SQL interval field qualifier (interval.md §6.1): its persisted code,
    // its name as written and displayed, its least-significant kept field, and whether a:b reads
    // as mm:ss.
    type intervalQualifier struct {
    \tcode  uint8
    \tname  string
    \tleast string
    \tmmSS  bool
    }

    // intervalQualifiers are the thirteen interval qualifiers, by ascending code
    // (intervalQualifiers[code-1]).
    var intervalQualifiers = []intervalQualifier{
    #{tables['qualifier'].map { |q| %(\t{code: #{q['code']}, name: "#{q['name']}", least: "#{q['least']}", mmSS: #{mm_ss(q)}},) }.join("\n")}
    }
  GO
end

# --- TypeScript ----------------------------------------------------------------

