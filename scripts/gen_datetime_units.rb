# --- driver --------------------------------------------------------------------

def main
  check = ARGV.include?("--check")
  max, tables = load_tables
  stale = []
  TARGETS.each do |rel, builder|
    path = File.join(REPO, rel)
    content = send(builder, max, tables)
    if check
      current = File.exist?(path) ? File.read(path) : nil
      stale << rel unless current == content
    else
      File.write(path, content)
      puts "wrote #{rel}"
    end
  end
  return unless check

  unless stale.empty?
    stale.each { |rel| warn "STALE: #{rel} — run 'mise run codegen'" }
    exit 1
  end
  puts "OK: #{TARGETS.length} generated files current " \
       "(#{tables['delta'].length} delta tokens, #{tables['date'].length} date tokens, " \
       "#{tables['qualifier'].length} interval qualifiers)"
end

main
