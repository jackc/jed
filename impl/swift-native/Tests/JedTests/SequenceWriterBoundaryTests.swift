import XCTest
@testable import Jed

final class SequenceWriterBoundaryTests: XCTestCase {
    private func blocked(_ session: Session, _ sql: String, file: StaticString = #filePath, line: UInt = #line) {
        XCTAssertThrowsError(try session.execute(sql), file: file, line: line) {
            XCTAssertEqual(($0 as? JedError)?.code, "55P03", sql, file: file, line: line)
        }
    }

    func testPrivateSequenceProofAndSelectedMainDefaultsUseDifferentWriterGates() throws {
        let database = try Database(), writer = try database.session()
        var options = SessionOptions(); options.lockTimeoutMilliseconds = 10
        let privateSession = try database.session(options: options)
        defer { privateSession.close(); writer.close(); try? database.close() }
        try writer.execute("CREATE SEQUENCE shared_seq")
        try writer.execute("CREATE VIEW sequence_source AS SELECT nextval('shared_seq') AS value")
        try privateSession.execute("CREATE TEMP TABLE scratch (id i64 GENERATED BY DEFAULT AS IDENTITY, value i64 DEFAULT nextval('shared_seq'))")
        try privateSession.execute("CREATE TEMP VIEW scratch_view AS SELECT id, value FROM scratch")
        try privateSession.execute("ALTER VIEW scratch_view ALTER value SET DEFAULT nextval('shared_seq')")
        let version = database.version
        try writer.begin()
        // Only the selected identity default advances, so the main writer can
        // stay held while the private table and private sequence publish.
        try privateSession.execute("INSERT INTO scratch(value) VALUES (7)")
        try privateSession.execute("INSERT INTO scratch VALUES (nextval('scratch_id_seq'), 8)")
        try privateSession.execute("INSERT INTO scratch_view VALUES (20, 9)")
        try privateSession.execute("UPDATE scratch SET value = 10")
        XCTAssertEqual(database.version, version)
        blocked(privateSession, "INSERT INTO scratch DEFAULT VALUES")
        blocked(privateSession, "INSERT INTO scratch_view DEFAULT VALUES")
        blocked(privateSession, "INSERT INTO scratch(value) SELECT value FROM sequence_source")
        blocked(privateSession, "UPDATE scratch SET value = 11 RETURNING nextval('shared_seq')")
        blocked(privateSession, "INSERT INTO scratch VALUES (nextval('scratch_' || 'id_seq'), 12)")
        XCTAssertEqual(database.version, version)
        try writer.rollback()
        try privateSession.execute("INSERT INTO scratch DEFAULT VALUES")
        XCTAssertEqual(database.version, version + 1)
    }

    func testChecksAndReferentialDefaultActionsRequireSharedAdmission() throws {
        let database = try Database(), writer = try database.session()
        var options = SessionOptions(); options.lockTimeoutMilliseconds = 10
        let privateSession = try database.session(options: options)
        defer { privateSession.close(); writer.close(); try? database.close() }
        try writer.execute("CREATE SEQUENCE shared_seq")
        try privateSession.execute("CREATE TEMP TABLE checked (value i64 CHECK (nextval('shared_seq') > 0))")
        try privateSession.execute("CREATE TEMP TABLE parent (id i64 PRIMARY KEY)")
        try privateSession.execute("CREATE TEMP TABLE child (id i64 DEFAULT nextval('shared_seq') REFERENCES parent(id) ON DELETE SET DEFAULT)")
        try privateSession.execute("INSERT INTO parent VALUES (1)")
        try privateSession.execute("INSERT INTO child VALUES (1)")
        let version = database.version
        try writer.begin()
        blocked(privateSession, "INSERT INTO checked VALUES (1)")
        blocked(privateSession, "DELETE FROM parent")
        XCTAssertEqual(database.version, version)
        try writer.rollback()
    }
}
